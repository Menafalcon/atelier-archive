/** Sync user-published thrift listings to the front of PRODUCTS. */
export function syncUserListings(userListings = []) {
  const valid = Array.isArray(userListings) ? userListings : [];
  PRODUCTS.length = 0;
  for (const item of valid) {
    if (!item || !item.id) continue;
    PRODUCTS.push({
      ...item,
      isUserListing: true,
      soldBy: item.soldBy || 'individual',
      seller: item.seller || {
        id: 'community',
        type: 'individual',
        name: 'Community Seller',
        handle: '@fripe.tn',
        location: 'Tunis',
        rating: 5.0,
        reviews: 1,
        sales: 1,
        joined: '2026',
        response: 'usually within 1 hour',
        photoStyle: 'phone',
        fulfilment: 'seller',
        blurb: 'Community member listing items directly on Atelier Archive.',
      },
    });
  }
  for (const item of BASE_PRODUCTS) {
    PRODUCTS.push(item);
  }
}

