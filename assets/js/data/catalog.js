/**
 * Local mirrored photography (assets/img). Extra arguments are accepted so call
 * sites stay readable, but each mirrored asset is a single master file.
 */
export function img(id) {
  if (!id) return 'assets/img/1523381210434-271e8be1f52b.jpg';
  const s = String(id).trim();
  if (
    s.startsWith('data:') ||
    s.startsWith('http://') ||
    s.startsWith('https://') ||
    s.startsWith('blob:') ||
    s.startsWith('assets/') ||
    s.startsWith('/')
  ) {
    return s;
  }
  return `assets/img/${s}.jpg`;
}

